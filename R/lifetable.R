#' Full life tables from child or child/adult mortality
#'
#' @description Generate complete life tables, single-year (ages 0, 1, ..., 109, 110+) or abridged (age groups 0, 1-4, 5-9, ..., 105-109, 110+), from child mortality, 5q0, or child and adult mortality, 5q0 and 45q15, using the SVD-Comp model. The arguments are those of \code{qx()}; the tables can be printed, used in R, or written to Excel, CSV, fixed-column text or JSON files.
#' @author Samuel J. Clark, \email{work@samclark.net}
#'
#' @param sex Character: 'female' or 'male' (not case sensitive).
#' @param cm Decimal: the input value(s) for 5q0; either a single value or a vector of values, one life table for each. See \code{\link{qx}} for the allowed range.
#' @param smooth Boolean: use either smooth or raw SVD-derived components. Default is TRUE.
#' @param out5 Boolean: abridged life tables in standard five-year age groups (TRUE) or single-year life tables (FALSE). Default is TRUE.
#' @param am Optional decimal: input value(s) for 45q15, the same number of values as cm. If not given, 45q15 is predicted from 5q0.
#' @param modsv Optional integer: the version of the calibration models; see \code{\link{qx}}. Default is 2026.
#' @param match.inputs Boolean: make each schedule reproduce its inputs exactly; see \code{\link{qx}}. Default is TRUE.
#' @param radix Decimal: the number of births the life tables start with, l0. Default is 100,000.
#' @param file Optional character: one or more file names to write the life tables to; the format of each follows its extension: .xlsx (Excel), .csv, .txt (fixed-column text) or .json. See \code{\link{writeLifetables}}. Default is NULL (no file).
#' @return An object of class \code{lifetables}: a list with \code{summary}, a data frame with one row for each life table (its id, sex, inputs, settings, the 5q0 and 45q15 of the life table, and e0), and \code{tables}, a named list of the life tables. Each life table is a data frame with columns age (the age group), x (its starting age), n (its width; NA for the open age group), nmx, nqx, nax, lx, ndx, nLx, Tx and ex. Printing shows the tables in fixed columns; \code{as.data.frame()} gives all the tables in one long data frame.
#'
#' @details
#' The life tables are built from the single-year schedule of 1qx generated by \code{qx()}; for
#' abridged tables, nqx are the products of the single-year values over each age group, as in
#' \code{\link{q1to5}}. The average number of years lived in an age group by those who die in it,
#' nax, follows standard conventions:
#'
#' * age 0 (both kinds of table): the Coale-Demeny rule for 1a0 (West model; Coale and Demeny
#'   1983, United Nations 1983): for 1q0 < 0.1, 0.0425 + 2.875 1q0 for males and
#'   0.05 + 3.0 1q0 for females; otherwise 0.33 for males and 0.35 for females;
#' * ages 1-4 (abridged tables): the Coale-Demeny rule for 4a1: for 1q0 < 0.1,
#'   1.653 - 3.013 1q0 for males and 1.524 - 1.627 1q0 for females; otherwise 1.352 for males
#'   and 1.361 for females;
#' * five-year age groups 5-9 to 105-109 (abridged tables): 2.5 years;
#' * single years of age 1 to 109 (single-year tables): 0.5 years, as in the single-year life
#'   tables of the Human Mortality Database;
#' * the open age group 110+: the death rate at age 109, m109 = 1q109/(1 - 0.5 1q109), continues,
#'   so that 110a+ = e110 = 1/m109 and L110+ = l110/m109, in both kinds of table.
#'
#' Then nmx = ndx/nLx, with nLx = n l(x+n) + nax ndx; Tx is the sum of nLx from age x on, and
#' ex = Tx/lx.
#'
#' @references Coale, A. J. and P. Demeny (1983) \emph{Regional Model Life Tables and Stable Populations}, 2nd edition, Academic Press. United Nations (1983) \emph{Manual X: Indirect Techniques for Demographic Estimation}. Preston, S. H., P. Heuveline and M. Guillot (2001) \emph{Demography: Measuring and Modeling Population Processes}, Blackwell.
#' @examples
#' lt <- lifetable("female",0.05)
#' lt
#' lifetable("male",c(0.01,0.1),am=c(0.15,0.35),out5=FALSE)$summary
#' lifetable("female",0.05,file=file.path(tempdir(),"female-0.05.csv"))
#' @seealso \code{\link{lifetableBatch}} for many life tables from a file, and \code{\link{writeLifetables}}.
#' @export
lifetable <- function(sex,cm,smooth=TRUE,out5=TRUE,am=NULL,modsv=2026,match.inputs=TRUE,radix=100000,file=NULL) {

  # sex, cm, smooth, am, modsv, match.inputs: as in qx()
  # out5: boolean, abridged (TRUE) or single-year (FALSE) life tables
  # radix: l0
  # file: optional file name(s) to write the life tables to

  if (!is.logical(out5) || length(out5) != 1 || is.na(out5))
    stop('<out5> must be TRUE or FALSE')
  checkRadix(radix)

  # the single-year schedules (qx() checks the other arguments)
  q1 <- qx(sex,cm,smooth=smooth,out5=FALSE,am=am,modsv=modsv,match.inputs=match.inputs)
  sex <- tolower(sex)
  ids <- colnames(q1)

  # one life table for each schedule
  tables <- list()
  for (i in 1:ncol(q1)) {
    tables[[i]] <- ltFromQ(q1[,i],sex,out5,radix)
  }
  names(tables) <- ids

  # summary: inputs, settings and results of each life table
  summary <- data.frame(
    id = ids,
    sex = sex,
    table = ifelse(out5,"abridged","single-year"),
    cm = cm,
    am = if (is.null(am)) NA else am,
    modsv = modsv,
    smooth = smooth,
    match.inputs = match.inputs,
    stringsAsFactors = FALSE
  )
  summary <- cbind(summary,ltResults(tables))
  rownames(summary) <- NULL

  lt <- structure(list(summary=summary,tables=tables),class="lifetables")
  if (!is.null(file)) {
    writeLifetables(lt,file)
  }
  return(lt)

}

# check the radix
checkRadix <- function(radix) {
  if (!is.numeric(radix) || length(radix) != 1 || is.na(radix) || radix <= 0)
    stop('<radix> must be a positive number')
}

# the 5q0, 45q15 and e0 of a list of life tables (each table's own values)
ltResults <- function(tables) {
  data.frame(
    cm.lt = sapply(tables,function(t) 1 - t$lx[t$x == 5]/t$lx[1]),
    am.lt = sapply(tables,function(t) 1 - t$lx[t$x == 60]/t$lx[t$x == 15]),
    e0 = sapply(tables,function(t) t$ex[1]),
    row.names = NULL
  )
}

# Coale-Demeny 1a0 and 4a1 (West), from 1q0
cdA0 <- function(q0,sex) {
  if (sex == "male") {
    a0 <- ifelse(q0 < 0.1,0.0425 + 2.875*q0,0.33)
  } else {
    a0 <- ifelse(q0 < 0.1,0.05 + 3.000*q0,0.35)
  }
  return(a0)
}
cdA1 <- function(q0,sex) {
  if (sex == "male") {
    a1 <- ifelse(q0 < 0.1,1.653 - 3.013*q0,1.352)
  } else {
    a1 <- ifelse(q0 < 0.1,1.524 - 1.627*q0,1.361)
  }
  return(a1)
}

# a life table from one single-year schedule of 1qx, ages 0-109: single-year or abridged
ltFromQ <- function(q1,sex,out5,radix) {

  q1 <- as.numeric(q1)
  q0 <- q1[1]

  if (out5) {
    # abridged: age groups 0, 1-4, 5-9, ..., 105-109, 110+
    q <- as.numeric(q1to5(q1)[,1])
    x <- c(0,1,seq(5,110,5))
    n <- c(1,4,rep(5,21),NA)
    age <- c("0","1-4",paste(seq(5,105,5),"-",seq(9,109,5),sep=""),"110+")
    a <- c(cdA0(q0,sex),cdA1(q0,sex),rep(2.5,21),NA)
  } else {
    # single years: ages 0, 1, ..., 109, 110+
    q <- c(q1,1)
    x <- 0:110
    n <- c(rep(1,110),NA)
    age <- c(as.character(0:109),"110+")
    a <- c(cdA0(q0,sex),rep(0.5,109),NA)
  }
  k <- length(q)

  # survivors and deaths
  l <- radix*cumprod(c(1,1 - q[-k]))
  d <- l*q

  # person-years lived in the closed age groups
  L <- n*(l - d) + a*d
  # open age group: the death rate at age 109 continues (from the single-year schedule, so that
  # single-year and abridged tables share the same open age group)
  m.open <- q1[110]/(1 - 0.5*q1[110])
  L[k] <- l[k]/m.open
  a[k] <- 1/m.open

  m <- d/L
  T <- rev(cumsum(rev(L)))
  e <- T/l

  lt <- data.frame(age=age,x=x,n=n,nmx=m,nqx=q,nax=a,lx=l,ndx=d,nLx=L,Tx=T,ex=e,stringsAsFactors=FALSE)
  return(lt)

}

#' @export
print.lifetables <- function(x,...) {
  n <- length(x$tables)
  cat("SVD-Comp life tables:",n,ifelse(n == 1,"table","tables"),"\n\n")
  show <- if (n <= 3) 1:n else 1
  for (i in show) {
    cat(formatLifetable(x,i),sep="\n")
    cat("\n")
  }
  if (n > 3) {
    cat("... and",n - 1,"more life tables: see x$tables, or write them to a file with writeLifetables().\n\n")
  }
  cat("Summary\n")
  print(utils::head(x$summary,20),row.names=FALSE)
  if (nrow(x$summary) > 20) {
    cat("... and",nrow(x$summary) - 20,"more rows: see x$summary\n")
  }
  invisible(x)
}

#' @export
as.data.frame.lifetables <- function(x,...) {
  rows <- lapply(seq_along(x$tables),function(i) {
    cbind(x$summary[rep(i,nrow(x$tables[[i]])),,drop=FALSE],x$tables[[i]])
  })
  out <- do.call(rbind,rows)
  rownames(out) <- NULL
  return(out)
}
